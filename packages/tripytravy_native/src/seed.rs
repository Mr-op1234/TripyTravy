/// Reconstructs the 32-byte CompiledSecretSeed in a stack-allocated Zeroizing buffer.
/// Automatically scrubs RAM upon scope exit.
pub fn reconstruct_secret_seed() -> Zeroizing<[u8; 32]> {
    let mut seed = Zeroizing::new([0u8; 32]);
    for i in 0..32 {
        let a = SHARD_0[i] ^ SHARD_1[(i * 7 + 3) & 31];
        let b = SHARD_2[(i * 11 + 5) & 31].wrapping_add(SHARD_3[(31 - i) & 31]);
        let mixed = a.wrapping_add(b).rotate_left(((i % 7) + 1) as u32);
        seed[i] = mixed ^ (0x5A_u8.wrapping_mul((i as u8).wrapping_add(1)));
    }
    seed
}
